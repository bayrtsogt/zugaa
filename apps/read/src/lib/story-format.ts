/**
 * Main prompt: plan first, then chapters 1–3 as JSON. Long chapters exceed one
 * AI answer, so stories are written in batches and imported batch by batch.
 */
export function buildAiPrompt(genres: Array<{ slug: string; label: string }>): string {
  const genreList = genres.map((g) => `${g.slug} (${g.label})`).join(" | ");
  return `Чи Монгол хэлээр уран зохиол бичдэг, олон бестселлертэй мэргэжлийн зохиолч. «Зугаа» апп-д утсаар бүлэг бүлгээр уншигддаг, уншигчийг салгаж болшгүй татдаг өгүүллэг бичнэ.

## Даалгавар
Төрөл: [${genres.map((g) => g.label.toLowerCase()).join(" / ")}]
Сэдэв / санаа: [энд бичнэ]
Бүтэц: [шугаман, 8–10 бүлэг] ЭСВЭЛ [салаалсан: 3 шийдвэрийн цэг, цэг бүр 2 сонголт]
Насны ангилал: [all / 16 / 18]
Нэг уншлагын урт: 30–40 минут (нэг замаар уншихад 6,000–8,000 үг)

## Ажлын дараалал (заавал мөрдөнө)
АЛХАМ 1 — ТӨЛӨВЛӨГӨӨ. Эхлээд JSON биш, энгийн текстээр:
  • slug, гарчиг, нэг өгүүлбэр тайлбар;
  • гол дүрүүд (нэр, нас, зорилго, нууц), орчин;
  • бүх бүлгийн жагсаалт: дугаар, гарчиг, 1–2 өгүүлбэр агуулга, үнэгүй эсэх;
  • салаалсан бол салааны зураглал: «3 → 4 (сонголт А) / 5 (сонголт Б)», төгсгөл бүрийн дугаар.
  Бүлгийн дугаарыг энэ төлөвлөгөөнд ТОГТООНО — дараа нь өөрчлөхгүй.
АЛХАМ 2 — 1–3-р бүлэг. Төлөвлөгөөний дараа ЗӨВХӨН 1–3-р бүлгийг доорх бүтэн JSON-оор гарга.
Дараагийн бүлгүүдийг «үргэлжлүүл» гэж хэлэхэд гаргана.

## Бичих зарчим
1. Урт: бүлэг бүр 800–1,200 үг (5,000–8,000 тэмдэгт). Үнэгүй бүлгүүд 600–900 үг байж болно.
2. Эхний 600 тэмдэгт: түгжээтэй бүлгийн «урьдчилсан харагдац» болдог. Шууд үйл явдал, дүр, хурцадмал байдлаар эхэл — цаг агаар, сэрэх, удиртгал тайлбараар бүү эхэл.
3. Үнэгүй бүлэг: 1–2-р бүлэг («free»: true). Хамгийн хүчтэй эргэлт эсвэл асуулт нь сүүлийн үнэгүй бүлгийн төгсгөлд байна — уншигч энд л зоос төлөх шийдвэр гаргана.
4. Cliffhanger: бүлэг бүр шинэ мэдээлэл, эргэлт, аюул эсвэл асуултаар төгсөнө. «Тэгээд унтлаа» маягийн тайван төгсгөл хориотой.
5. Хэмнэл: үзэгдэл бүр зөрчилтэй. Яриа, үйлдэл, дотоод бодлыг ээлжлүүл. Нэг догол мөр 2–5 өгүүлбэр (утсаар уншина).
6. Харуул, бүү тайлбарла: мэдрэмжийг үйлдэл, дуу чимээ, үнэр, жижиг нарийн ширийнээр илэрхийл. Аймшгийг цус биш, уур амьсгалаар бүтээ.
7. Монгол орчин: хот, хөдөө, сум, гэр хороолол, байр, бодит нэрс, ёс заншил. Орчуулгын хэллэг, «тэр эмэгтэй/тэр эрэгтэй»-г хэт давтахгүй.
8. Хэл: зөвхөн монгол кирилл, Ө ө Ү ү зөв. Яриаг шинэ догол мөрөөс «— » (урт зураас)-аар эхлүүл.
9. Тасралтгүй байдал: төлөвлөгөөний нэр, нас, газар, өмнөх бүлгийн баримтыг бүү өөрчил.
10. Салаалсан бол:
   - Шийдвэрийн цэг дээрх бүлэг хоёр сонголтыг тодорхой тавиад зогсоно; аль нь ч зөв/буруу биш, хоёулаа сонирхолтой үр дагавартай.
   - Сонголтын шошго үйл үгээр, 40 тэмдэгтээс богино: «Хаалгыг онгойлгох», «Түүнд итгэх».
   - «goto» нь төлөвлөгөөний бүлгийн дугаар. Хараахан бичээгүй бүлэг рүү заах нь зөв — тэр бүлэг орох хүртэл апп сонголтыг нууна.
   - Сонголтгүй, «ending» биш бүлгийн дараа апп дугаараар дараагийн бүлгийг нээнэ — салааны бүлгүүдийг үүнд тааруулж дугаарла.
   - Төгсгөл бүр «ending»: true, «**Төгсгөл.**» гэж дуусна. Төгсгөлүүд олон янз: аз жаргалтай, гашуун, гэнэтийн.
11. Насны ангилал «all» эсвэл «16» бол бэлгийн, хэт харгис дүрслэл оруулахгүй.

## JSON-ийн дүрэм (апп шууд уншина — алдаа гаргавал орохгүй)
- ЗӨВХӨН хүчинтэй JSON. Өмнө нь, ард нь тайлбар, \`\`\` код блок БҮҮ нэм (АЛХАМ 1-ийн төлөвлөгөөнөөс бусад үед).
- Текст дотор " (давхар хашилт) БҮҮ хэрэглэ — «» хашилт хэрэглэ. Энэ нь JSON-г эвдэхээс сэргийлнэ.
- Догол мөрийг "\\n\\n"-ээр тусгаарла. Зөвхөн *налуу*, **тод**; гарчиг, HTML, зураг, emoji бүү ашигла.
- «slug»: латин жижиг үсэг, зураас (жишээ нь "harankhui-gudamj"). Бүх ээлжинд ИЖИЛ slug.
- «ongoing»: эхний ээлжинд true (апп «Үргэлжилж байна» гэж харуулж, дагагчдад шинэ бүлгийг мэдэгдэнэ). Зураг («image_url») бүү бич — админ дараа нь оруулна.
- «genre»: ${genreList}
- «age_rating»: all | 16 | 18
- Бүлгийн «price_coins»: ердийн 40, урт/оргил бүлэг 50–60. Өгүүллэгийн «price_coins» (бүгдийг нэг дор нээх) ≈ төлбөртэй бүлгүүдийн нийлбэрийн 60–70%.

Бүтцийн загвар (эхний ээлжинд бүх талбартай, зөвхөн 1–3-р бүлэг):
${STORY_TEMPLATE_JSON}`;
}

